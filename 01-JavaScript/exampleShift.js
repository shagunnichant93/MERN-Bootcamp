let fruits = ["Apple", "Banana", "Cherry", "Date", "Elderberry"];
console.log(`Initial fruits: ${fruits[0]}
    ${fruits[1]}
    ${fruits[2]}
    ${fruits[3]}
    ${fruits[4]}`);
let removed = fruits.shift();
console.log("------------------");
console.log(`Fruits after shifting: ${fruits[0]}
    ${fruits[1]}
    ${fruits[2]}
    ${fruits[3]}`);
console.log("------------------");
console.log(`Removed fruit: ${removed}`);
console.log("------------------");
console.log(`Total fruits in the array: ${fruits.length}`);

